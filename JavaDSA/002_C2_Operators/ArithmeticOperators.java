public class ArithmeticOperators {

    static void main(String[] args) {
        int A = 5 ;
        int B = 5 ;

        System.out.println("Answers of the all Arithmetic Operators :");
        System.out.println("A+B is = : "+(A+B));
        System.out.println("A-B is = : "+(A-B));
        System.out.println("A*B is = : "+(A*B));
        System.out.println("A/B is = : "+(A/B));
        System.out.println("A%B is = : "+(A%B));
    }
}
