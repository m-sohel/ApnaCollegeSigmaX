public class AssignmentOpr {
    public static void main(String[] args) {

    /*  =    assignment
        +=   add and assign
        -=   subtract and assign
        *=   multiply and assign
        /=   divide and assign      
        %=   modulo (remainder & assign)   */
     
        int a = 20;
        System.out.println("the curren value of A : "+a);
          
        a+=40;
        System.out.println("the result after a+=40 : "+a);

        a-=10;
        System.out.println("the result after a-=10 : "+a);

        a*=10;
        System.out.println("the result after a*=10 : "+a);

        a/=10;
        System.out.println("the result after a/=10 : "+a);

        a%=10;
        System.out.println("the result after a%=10 : "+a);

    }
}
